/**
 * Bundles Heroicons outline SVG bodies (MIT) into a TS module for inline HUD icons.
 * @see https://heroicons.com
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, '..');
const repoRoot = join(pkgRoot, '..', '..');
const require = createRequire(import.meta.url);
const iconsPath = require.resolve('@iconify-json/heroicons-outline/icons.json');
const solidIconsPath = require.resolve('@iconify-json/heroicons-solid/icons.json');
const { icons } = JSON.parse(readFileSync(iconsPath, 'utf8'));
const { icons: solidIcons } = JSON.parse(readFileSync(solidIconsPath, 'utf8'));

/** Presenter icon key → Heroicons outline (@iconify-json/heroicons-outline) icon id. */
const MAP = {
  view: 'eye',
  pointer: 'cursor-arrow-rays',
  send: 'paper-airplane',
  'caret-down': 'chevron-down',
  check: 'check',
  remove: 'x-mark',
  pause: 'pause',
  play: 'play',
  stop: 'stop',
  copy: 'document-duplicate',
  download: 'arrow-down-tray',
  message: 'chat-bubble-left-ellipsis',
  gear: 'cog-6-tooth',
  layout: 'squares-2x2',
  trash: 'trash',
  help: 'question-mark-circle',
  'caret-right': 'chevron-right',
};

/** Outline key → solid body for toolbar toggle buttons (filled when active). */
const TOGGLE_SOLID_MAP = {
  message: 'chat-bubble-left-ellipsis',
  view: 'eye',
  gear: 'cog-6-tooth',
};

const bodies = {};
for (const [key, id] of Object.entries(MAP)) {
  const entry = icons[id];
  if (entry === undefined) throw new Error(`missing heroicon: ${id}`);
  bodies[key] = minifyOutlineBody(entry.body);
}

const solidBodies = {};
for (const [key, id] of Object.entries(TOGGLE_SOLID_MAP)) {
  const entry = solidIcons[id];
  if (entry === undefined) throw new Error(`missing heroicon solid: ${id}`);
  solidBodies[key] = entry.body;
}

/** Drop attrs the HUD svg root supplies via CSS (smaller embedded SDK). */
function minifyOutlineBody(body) {
  return body
    .replace(/\s*fill="none"/g, '')
    .replace(/\s*stroke="currentColor"/g, '')
    .replace(/\s*stroke-linecap="round"/g, '')
    .replace(/\s*stroke-linejoin="round"/g, '')
    .replace(/\s*stroke-width="(?:1\.5|2)"/g, '');
}

const out = `/** Generated by scripts/embed-heroicons.mjs - do not edit by hand. */
/** Heroicons outline - MIT, https://heroicons.com */
export const HERO_ICON_BODIES = ${JSON.stringify(bodies)} as const;
export type HeroIconBodyKey = keyof typeof HERO_ICON_BODIES;
/** Solid variants for toolbar toggles - shown when data-active="1". */
export const HERO_ICON_SOLID_BODIES = ${JSON.stringify(solidBodies)} as const;
export type HeroIconSolidBodyKey = keyof typeof HERO_ICON_SOLID_BODIES;
`;

const outPath = join(pkgRoot, 'src', 'presenter', 'presenter-heroicons-data.ts');
writeFileSync(outPath, out, 'utf8');
execSync(`pnpm exec prettier --write --log-level silent "${outPath}"`, {
  cwd: repoRoot,
  stdio: 'inherit',
});
console.log(`wrote presenter-heroicons-data.ts (${Object.keys(bodies).length} icons)`);
